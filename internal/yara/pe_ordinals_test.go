package yara

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"
)

// The ordinal names of pe_ordinals.go come from the export tables of the
// Windows DLLs themselves. OPENRMM_GENERATE_ORDINALS=1 on Windows rewrites
// the file from this machine's System32.
func TestGenerateOrdinals(t *testing.T) {
	if os.Getenv("OPENRMM_GENERATE_ORDINALS") != "1" {
		t.Skip("set OPENRMM_GENERATE_ORDINALS=1 on Windows to regenerate pe_ordinals.go")
	}
	var b strings.Builder
	b.WriteString("package yara\n\n// Generated by TestGenerateOrdinals from the export tables of Windows'\n")
	b.WriteString("// ws2_32.dll, wsock32.dll and oleaut32.dll: the names of functions that\n")
	b.WriteString("// programs import by ordinal, for the import hash.\n\n")
	b.WriteString("var ordinalNames = map[string]map[uint16]string{\n")
	for _, dll := range []string{"oleaut32", "ws2_32", "wsock32"} {
		data, err := os.ReadFile(filepath.Join(os.Getenv("SystemRoot"), "System32", dll+".dll"))
		if err != nil {
			t.Fatal(err)
		}
		p := parsePE(data, false, 0)
		if p == nil || len(p.exports) == 0 {
			t.Fatal(dll, "has no exports")
		}
		names := map[uint16]string{}
		for _, x := range p.exports {
			if x.name != "" && x.ordinal <= 0xFFFF {
				names[uint16(x.ordinal)] = x.name
			}
		}
		ords := make([]int, 0, len(names))
		for o := range names {
			ords = append(ords, int(o))
		}
		slices.Sort(ords)
		fmt.Fprintf(&b, "\t%q: {\n", dll)
		for _, o := range ords {
			fmt.Fprintf(&b, "\t\t%d: %q,\n", o, names[uint16(o)])
		}
		b.WriteString("\t},\n")
		t.Logf("%s: %d named exports", dll, len(names))
	}
	b.WriteString("}\n")
	if err := os.WriteFile("pe_ordinals.go", []byte(b.String()), 0644); err != nil {
		t.Fatal(err)
	}
}
