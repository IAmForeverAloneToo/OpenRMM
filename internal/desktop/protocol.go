// Package desktop owns attended support sessions. Capture and input are OS adapters;
// this protocol contains no credential, shell, clipboard or filesystem operation.
package desktop

import (
	"bytes"
	"encoding/json"
	"errors"
	"image/jpeg"
	"io"
	"unicode/utf8"

	"github.com/IAmForeverAloneToo/OpenRMM/internal/protocol"
)

const MaxFrame = 1024 * 1024
const MaxWire = 1500000
const MaxWidth = 1280
const MaxHeight = 720

var ErrInvalid = errors.New("invalid or expired desktop session")
var ErrUnavailable = errors.New("desktop companion unavailable or already in use")

// Request is a session as the companion sees it. Display (an index into the
// displays the companion reported) and Quality are chosen in the dashboard
// and may change during the session.
type Request struct {
	ID      string `json:"id"`
	Actor   string `json:"actor"`
	Control bool   `json:"control"`
	Expires int64  `json:"expires"`
	Display int    `json:"display"`
	Quality string `json:"quality,omitempty"`
}

// Qualities are the capture profiles a session can use.
var Qualities = []string{"bandwidth", "balanced", "detail"}

// ValidQuality accepts a capture profile name ("" means balanced).
func ValidQuality(q string) bool {
	_, ok := profile(q)
	return ok || q == ""
}

// Display is one display the companion can share, as reported to the
// dashboard; a session names it by Index.
type Display struct {
	Index   int  `json:"index"`
	Left    int  `json:"left"`
	Top     int  `json:"top"`
	Width   int  `json:"width"`
	Height  int  `json:"height"`
	Primary bool `json:"primary"`
}

// DisplaysValid checks a reported display list: at most 16, indexed in
// order, one primary.
func DisplaysValid(d []Display) bool {
	if len(d) > 16 {
		return false
	}
	primary := 0
	for i, v := range d {
		r := region{v.Left, v.Top, v.Left + v.Width, v.Top + v.Height}
		if v.Index != i || !r.valid() || v.Width > 32768 || v.Height > 32768 {
			return false
		}
		if v.Primary {
			primary++
		}
	}
	return len(d) == 0 || primary == 1
}

type Input struct {
	Kind   string `json:"kind"`
	X      int    `json:"x,omitempty"`
	Y      int    `json:"y,omitempty"`
	Button int    `json:"button,omitempty"`
	Key    uint16 `json:"key,omitempty"`
	Text   string `json:"text,omitempty"`
	Ctrl   bool   `json:"ctrl,omitempty"`
	Alt    bool   `json:"alt,omitempty"`
	Shift  bool   `json:"shift,omitempty"`
}

// Keys are complete taps/chords, not persistent key-down state. A lost reply
// cannot leave a remotely held modifier or mouse button down.
func (v Input) Valid() bool {
	if v.X < 0 || v.X > 65535 || v.Y < 0 || v.Y > 65535 {
		return false
	}
	switch v.Kind {
	case "move", "click", "double-click", "wheel":
		return v.Text == "" && v.Key == 0 && !v.Ctrl && !v.Alt && !v.Shift &&
			(v.Kind == "move" && v.Button == 0 || (v.Kind == "click" || v.Kind == "double-click") && v.Button >= 1 && v.Button <= 3 || v.Kind == "wheel" && (v.Button == -1 || v.Button == 1))
	case "text":
		return v.X == 0 && v.Y == 0 && v.Button == 0 && v.Key == 0 && !v.Ctrl && !v.Alt && !v.Shift && utf8.ValidString(v.Text) && len(v.Text) > 0 && len(v.Text) <= 128 && !bytes.ContainsRune([]byte(v.Text), 0)
	case "key":
		return v.X == 0 && v.Y == 0 && v.Button == 0 && v.Text == "" && allowedKey(v.Key)
	}
	return false
}
func allowedKey(k uint16) bool {
	return k == 8 || k == 9 || k == 13 || k == 27 || k == 32 || k >= 33 && k <= 40 || k == 45 || k == 46 || k >= 48 && k <= 90 || k >= 112 && k <= 123
}

type Batch struct {
	Sequence uint64  `json:"sequence"`
	Events   []Input `json:"events"`
}

func (b Batch) Valid() bool {
	if b.Sequence == 0 || b.Sequence > 1000000 || len(b.Events) == 0 || len(b.Events) > 16 {
		return false
	}
	for _, v := range b.Events {
		if !v.Valid() {
			return false
		}
	}
	return true
}

// Exchange is also the private local pipe protocol. Peer is generated by the
// agent per pipe connection; the companion cannot choose it on the server.
type Exchange struct {
	Peer  string `json:"peer,omitempty"`
	Ready bool   `json:"ready"`
	ID    string `json:"id,omitempty"`
	State string `json:"state,omitempty"`
	Frame []byte `json:"frame,omitempty"`
	// Displays is the current display layout (companions since release 30).
	Displays []Display `json:"displays,omitempty"`
}
type Reply struct {
	Request *Request `json:"request,omitempty"`
	Inputs  []Input  `json:"inputs,omitempty"`
}

func (p Exchange) Valid() bool {
	if !p.Ready {
		return p.Peer == "" && p.ID == "" && p.State == "" && len(p.Frame) == 0 && len(p.Displays) == 0
	}
	if !DisplaysValid(p.Displays) {
		return false
	}
	if !protocol.ValidID(p.Peer) {
		return false
	}
	if p.ID == "" {
		return p.State == "" && len(p.Frame) == 0
	}
	if !protocol.ValidID(p.ID) {
		return false
	}
	switch p.State {
	case "waiting", "denied", "ended", "unavailable":
		return len(p.Frame) == 0
	case "active":
		return len(p.Frame) == 0 || FrameValid(p.Frame)
	}
	return false
}
func FrameValid(b []byte) bool {
	if len(b) == 0 || len(b) > MaxFrame {
		return false
	}
	c, e := jpeg.DecodeConfig(bytes.NewReader(b))
	return e == nil && c.Width >= 1 && c.Height >= 1 && c.Width <= MaxWidth && c.Height <= MaxHeight
}
func Decode(b []byte, v any) error {
	if len(b) == 0 || len(b) > MaxWire {
		return ErrInvalid
	}
	d := json.NewDecoder(bytes.NewReader(b))
	d.DisallowUnknownFields()
	if d.Decode(v) != nil || d.Decode(new(any)) != io.EOF {
		return ErrInvalid
	}
	return nil
}
